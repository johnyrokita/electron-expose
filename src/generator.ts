import fsSync from "node:fs"
import fs from "node:fs/promises"
import path from "node:path"
import fg from "fast-glob"
import { createJiti } from "jiti"
import {
  Node,
  Project,
  SyntaxKind,
  type ClassDeclaration,
  type JSDocableNode,
  type MethodDeclaration,
  type SourceFile,
  type VariableDeclaration,
} from "ts-morph"
import type { ElectronExposeConfig } from "./index.js"

const DEFAULT_CONFIG_PATH = "electron-expose.config.ts"

const HEADER = "// Generated by electron-expose. Do not edit."

type GenerateOptions = {
  /**
   * Config file path. When omitted, `electron-expose.config.ts` is used if it
   * exists. A path given explicitly must exist.
   */
  configPath?: string
  cwd?: string
}

type ResolvedElectronExposeConfig = Required<
  Pick<ElectronExposeConfig, "outDir" | "globalApiName" | "routePrefix">
> &
  ElectronExposeConfig

/**
 * One exposed function or class method. Generated code refers to it through
 * its module export, so nothing about its signature is stored here.
 */
type ExposedRoute = {
  key: string
  sourcePath: string
  /** Exported variable name, or the exported class name for a method. */
  exportName: string
  /** Set when the route is a class method. */
  methodName?: string
  /** Leading JSDoc block, copied onto the generated renderer type. */
  docs?: string
  /** Node whose type is the route's signature. Only read by `list`. */
  node: Node
}

type RouteDiscovery = {
  cwd: string
  config: ResolvedElectronExposeConfig
  include: string | string[]
  routeFiles: string[]
  routes: ExposedRoute[]
}

type GenerateResult = {
  summary: string
  /** False when every generated file already had the right contents. */
  changed: boolean
}

const DEFAULTS = {
  outDir: "src/generated/electron-expose",
  globalApiName: "api",
  routePrefix: "electron-expose",
} satisfies Required<
  Pick<ElectronExposeConfig, "outDir" | "globalApiName" | "routePrefix">
>

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/

/** Generates the main, preload, and type files once. */
export async function generateElectronExpose(
  options: GenerateOptions = {},
): Promise<void> {
  const result = await generate(options)
  console.log(result.summary)
}

/**
 * Generates once, then regenerates whenever a TypeScript file under the
 * scanned directories changes. Returns a function that stops watching.
 *
 * Errors are printed instead of thrown, so a half-typed route does not end the
 * watcher. Config changes are not picked up until it is restarted.
 */
export async function watchElectronExpose(
  options: GenerateOptions = {},
): Promise<() => void> {
  const cwd = options.cwd ?? process.cwd()
  const config = await loadConfig(cwd, options.configPath)

  const run = async () => {
    try {
      const result = await generate(options)
      if (result.changed) console.log(result.summary)
    } catch (error) {
      console.error(error instanceof Error ? error.message : String(error))
    }
  }

  await run()

  // Generated files are skipped so our own writes never trigger a run.
  const outDir = path.resolve(cwd, config.outDir)
  const globalPath = resolveGlobalPath(cwd, config)
  let timer: NodeJS.Timeout | undefined
  let queue = Promise.resolve()

  const watchers = watchRoots(cwd, config).map((dir) =>
    fsSync.watch(dir, { recursive: true }, (_event, filename) => {
      if (!filename || !/\.tsx?$/.test(filename)) return
      const file = path.join(dir, filename)
      if (file === globalPath || isInside(outDir, file)) return
      if (file.split(path.sep).includes("node_modules")) return

      clearTimeout(timer)
      timer = setTimeout(() => {
        queue = queue.then(run)
      }, 100)
    }),
  )

  return () => {
    clearTimeout(timer)
    for (const watcher of watchers) watcher.close()
  }
}

/** Prints every discovered route with its renderer-facing signature. */
export async function listElectronExposeRoutes(
  options: GenerateOptions = {},
): Promise<void> {
  const discovery = await discoverRoutes(options)

  if (discovery.routes.length === 0) {
    console.log(renderNoRoutesMessage(discovery))
    return
  }

  const rows = [...discovery.routes]
    .sort((a, b) => a.key.localeCompare(b.key))
    .map((route) => {
      const source = path.relative(discovery.cwd, route.sourcePath)
      return `${route.key}  ${renderRouteSignature(route)}  ${source}`
    })

  console.log(rows.join("\n"))
}

async function generate(options: GenerateOptions): Promise<GenerateResult> {
  const discovery = await discoverRoutes(options)
  const { cwd, config, routes } = discovery

  if (routes.length === 0) throw new Error(renderNoRoutesMessage(discovery))

  const outDir = path.resolve(cwd, config.outDir)
  const modules = aliasModules(routes, cwd)
  const files: Array<[file: string, contents: string]> = [
    [path.join(outDir, "main.ts"), renderMain(routes, modules, outDir, config)],
    [path.join(outDir, "preload.ts"), renderPreload(config)],
    [path.join(outDir, "types.ts"), renderTypes(routes, modules, outDir)],
  ]

  const globalPath = resolveGlobalPath(cwd, config)
  if (globalPath) {
    files.push([globalPath, renderGlobal(globalPath, outDir, config)])
  }

  const written = await Promise.all(
    files.map(([file, contents]) => writeIfChanged(file, contents)),
  )

  return {
    summary: `Generated ${routes.length} route${routes.length === 1 ? "" : "s"} in ${path.relative(cwd, outDir)}`,
    changed: written.some(Boolean),
  }
}

/**
 * Writes a file only when its contents differ, so an unchanged run does not
 * touch mtimes and retrigger dev servers that watch the output directory.
 */
async function writeIfChanged(
  file: string,
  contents: string,
): Promise<boolean> {
  const existing = await fs.readFile(file, "utf8").catch(() => undefined)
  if (existing === contents) return false

  await fs.mkdir(path.dirname(file), { recursive: true })
  await fs.writeFile(file, contents, "utf8")
  return true
}

async function discoverRoutes(
  options: GenerateOptions,
): Promise<RouteDiscovery> {
  const cwd = options.cwd ?? process.cwd()
  const config = await loadConfig(cwd, options.configPath)
  const include = resolveInclude(cwd, config)
  const matched = await fg(include, {
    cwd,
    absolute: true,
    ignore: resolveExclude(cwd, config),
    onlyFiles: true,
  })
  // Sorted so generated output does not depend on file system order.
  const routeFiles = matched.sort()

  const project = new Project({
    tsConfigFilePath: findTsconfig(cwd, config.tsconfig),
    skipAddingFilesFromTsConfig: true,
  })

  // A route needs `exposed(` or `@expose`, so a file without the word cannot
  // have one. Checking the text first avoids parsing the rest of the tree.
  // `overwrite` only replaces the in-memory copy; nothing is saved to disk.
  const texts = await Promise.all(
    routeFiles.map((file) => fs.readFile(file, "utf8")),
  )
  const routes = routeFiles.flatMap((file, index) =>
    texts[index].includes("expose")
      ? scanSourceFile(
          project.createSourceFile(file, texts[index], { overwrite: true }),
        )
      : [],
  )
  validateRoutes(routes)

  return { cwd, config, include, routeFiles, routes }
}

function renderNoRoutesMessage(discovery: RouteDiscovery): string {
  const include = JSON.stringify(discovery.include)

  if (discovery.routeFiles.length === 0) {
    return `No source files matched ${include}.`
  }

  return [
    `No exposed routes found in ${discovery.routeFiles.length} matched source file${discovery.routeFiles.length === 1 ? "" : "s"}.`,
    `Matched ${include}, but did not find any @expose() decorators or exposed(...) functions.`,
  ].join("\n")
}

async function loadConfig(
  cwd: string,
  configPath?: string,
): Promise<ResolvedElectronExposeConfig> {
  const resolved = path.resolve(cwd, configPath ?? DEFAULT_CONFIG_PATH)

  if (!fsSync.existsSync(resolved)) {
    if (configPath) throw new Error(`Config file not found: ${configPath}`)
    return DEFAULTS
  }

  const jiti = createJiti(import.meta.url)
  const config = await jiti.import<ElectronExposeConfig>(resolved, {
    default: true,
  })
  return { ...DEFAULTS, ...config }
}

function resolveInclude(
  cwd: string,
  config: ElectronExposeConfig,
): string | string[] {
  if (config.routes) return config.routes
  if (config.include) return config.include

  const root = config.root ?? detectSourceRoot(cwd)
  return `${trimTrailingSlash(root)}/**/*.{ts,tsx}`
}

function resolveExclude(
  cwd: string,
  config: ResolvedElectronExposeConfig,
): string[] {
  const configured = Array.isArray(config.exclude)
    ? config.exclude
    : config.exclude
      ? [config.exclude]
      : []
  const relativeOutDir = path
    .relative(cwd, path.resolve(cwd, config.outDir))
    .replaceAll(path.sep, "/")

  return [
    "**/*.d.ts",
    "**/node_modules/**",
    "**/dist/**",
    "**/build/**",
    "**/out/**",
    "**/.vite/**",
    `${trimTrailingSlash(relativeOutDir)}/**`,
    ...configured,
  ]
}

/** Absolute path of the renderer global declaration, or undefined when disabled. */
function resolveGlobalPath(
  cwd: string,
  config: ResolvedElectronExposeConfig,
): string | undefined {
  if (config.rendererGlobal === false) return undefined
  return path.resolve(cwd, config.rendererGlobal ?? "src/renderer/global.d.ts")
}

/** Existing directories that contain every file the include globs can match. */
function watchRoots(
  cwd: string,
  config: ResolvedElectronExposeConfig,
): string[] {
  const bases = fg
    .generateTasks(resolveInclude(cwd, config), { cwd })
    .map((task) => path.resolve(cwd, task.base))

  return unique(bases).filter((dir) => fsSync.existsSync(dir))
}

function isInside(dir: string, file: string): boolean {
  return file.startsWith(`${dir}${path.sep}`)
}

function detectSourceRoot(cwd: string): string {
  for (const candidate of ["src", "app", "electron"]) {
    if (fsSync.existsSync(path.join(cwd, candidate))) return candidate
  }

  return "."
}

function trimTrailingSlash(value: string): string {
  return value.replace(/\/+$/, "")
}

function findTsconfig(cwd: string, configured?: string): string | undefined {
  const tsconfig = path.resolve(cwd, configured ?? "tsconfig.json")
  return fsSync.existsSync(tsconfig) ? tsconfig : undefined
}

function scanSourceFile(sourceFile: SourceFile): ExposedRoute[] {
  const routes: ExposedRoute[] = []
  const sourcePath = sourceFile.getFilePath()

  for (const declaration of sourceFile.getVariableDeclarations()) {
    const exposed = readExposedCall(declaration)
    if (!exposed) continue

    const statement = declaration.getFirstAncestorByKind(
      SyntaxKind.VariableStatement,
    )
    const name = declaration.getName()
    if (!statement?.isExported()) {
      throw new Error(
        `${sourcePath}: exposed variable "${name}" must be exported`,
      )
    }

    routes.push({
      key: exposed.key ?? name,
      sourcePath,
      exportName: name,
      docs: readDocs(statement),
      node: exposed.fn,
    })
  }

  for (const cls of sourceFile.getClasses()) {
    const className = cls.getName()
    if (!className) continue

    for (const method of cls.getMethods()) {
      const exposed = readExposeDecorator(method)
      if (!exposed) continue
      assertExposableMethod(cls, method)

      const methodName = method.getName()
      routes.push({
        key: exposed.key ?? methodName,
        sourcePath,
        exportName: className,
        methodName,
        docs: readDocs(method),
        node: method,
      })
    }
  }

  return routes
}

/**
 * Reads `exposed(fn)` or `exposed(nameOrOptions, fn)` from a variable
 * initializer. The function can be any expression, since generated code only
 * refers to the exported variable.
 */
function readExposedCall(
  declaration: VariableDeclaration,
): { key?: string; fn: Node } | undefined {
  const initializer = declaration.getInitializer()
  if (!Node.isCallExpression(initializer)) return undefined
  if (initializer.getExpression().getText() !== "exposed") return undefined

  const args = initializer.getArguments()
  if (args.length === 1 && !isKeyArg(args[0])) return { fn: args[0] }
  if (args.length === 2 && isKeyArg(args[0])) {
    return { key: readKeyArg(args[0], "exposed()"), fn: args[1] }
  }

  throw new Error(
    `${declaration.getSourceFile().getFilePath()}: exposed() expects a function, or a name/options object plus a function`,
  )
}

function readExposeDecorator(
  method: MethodDeclaration,
): { key?: string } | undefined {
  const decorator = method
    .getDecorators()
    .find((item) => item.getName() === "expose")
  if (!decorator) return undefined

  const arg = decorator.getCallExpression()?.getArguments()[0]
  return { key: arg ? readKeyArg(arg, "@expose()") : undefined }
}

function isKeyArg(arg: Node): boolean {
  return (
    Node.isStringLiteral(arg) ||
    Node.isNoSubstitutionTemplateLiteral(arg) ||
    Node.isObjectLiteralExpression(arg)
  )
}

/**
 * Reads the route key from a string or `{ name }` argument. Returns undefined
 * when an options object has no name, which falls back to the declared name.
 */
function readKeyArg(arg: Node, label: string): string | undefined {
  if (Node.isStringLiteral(arg) || Node.isNoSubstitutionTemplateLiteral(arg)) {
    return validateKey(arg.getLiteralText(), arg)
  }

  if (Node.isObjectLiteralExpression(arg)) {
    const prop = arg.getProperty("name")
    if (!prop) return undefined

    const init = Node.isPropertyAssignment(prop)
      ? prop.getInitializer()
      : undefined
    if (
      Node.isStringLiteral(init) ||
      Node.isNoSubstitutionTemplateLiteral(init)
    ) {
      return validateKey(init.getLiteralText(), arg)
    }
  }

  throw new Error(
    `${arg.getSourceFile().getFilePath()}: ${label} only accepts a string or { name: string }`,
  )
}

function validateKey(key: string, node: Node): string {
  if (!key.split(".").every((part) => IDENTIFIER.test(part))) {
    throw new Error(
      `${node.getSourceFile().getFilePath()}: invalid expose key "${key}"`,
    )
  }
  return key
}

/**
 * Generated code calls exposed methods on one instance created with no
 * arguments, so the class and the method both have to be reachable that way.
 */
function assertExposableMethod(
  cls: ClassDeclaration,
  method: MethodDeclaration,
): void {
  const sourcePath = cls.getSourceFile().getFilePath()
  const className = cls.getName()

  if (!cls.isExported()) {
    throw new Error(
      `${sourcePath}: class "${className}" contains exposed methods but is not exported`,
    )
  }

  const ctor = cls.getConstructors()[0]
  if (
    ctor &&
    ctor
      .getParameters()
      .some((param) => !param.hasQuestionToken() && !param.getInitializer())
  ) {
    throw new Error(
      `${sourcePath}: exposed class "${className}" must have a zero-argument constructor`,
    )
  }

  if (
    method.isStatic() ||
    method.getScope() !== "public" ||
    !Node.isIdentifier(method.getNameNode())
  ) {
    throw new Error(
      `${sourcePath}: exposed method "${className}.${method.getName()}" must be a public instance method with a plain name`,
    )
  }
}

/**
 * Returns the JSDoc block directly above a declaration, re-indented to column
 * 0. A block separated by a blank line is skipped, since that is usually a
 * file or section comment and not about this route.
 */
function readDocs(node: Node & JSDocableNode): string | undefined {
  const doc = node.getJsDocs().at(-1)
  if (!doc) return undefined

  const gap = node
    .getSourceFile()
    .getFullText()
    .slice(doc.getEnd(), node.getStart())
  if (/\n\s*\n/.test(gap)) return undefined

  return doc
    .getText()
    .split("\n")
    .map((line) => line.trim())
    .map((line, index) => (index > 0 ? ` ${line}` : line))
    .join("\n")
}

function validateRoutes(routes: ExposedRoute[]): void {
  const keys = new Set<string>()

  for (const route of routes) {
    if (keys.has(route.key))
      throw new Error(`Duplicate exposed route key "${route.key}"`)
    keys.add(route.key)
  }

  for (const key of keys) {
    const parts = key.split(".")
    for (let length = 1; length < parts.length; length++) {
      const parent = parts.slice(0, length).join(".")
      if (keys.has(parent)) {
        throw new Error(
          `Exposed route key "${parent}" conflicts with nested key "${key}"`,
        )
      }
    }
  }
}

/**
 * Maps each route source file to the namespace alias generated files import it
 * as, e.g. `src/main/routes/users.ts` becomes `m_src_main_routes_users`.
 *
 * The alias comes from the file's own path, so adding or removing a route file
 * does not rename the others. That keeps diffs small for projects that commit
 * generated files.
 */
function aliasModules(
  routes: ExposedRoute[],
  cwd: string,
): Map<string, string> {
  const modules = new Map<string, string>()
  const taken = new Set<string>()

  for (const sourcePath of unique(routes.map((route) => route.sourcePath))) {
    const base = `m_${path
      .relative(cwd, sourcePath)
      .replace(/\.tsx?$/, "")
      .replace(/\W/g, "_")}`

    // Two paths can flatten to the same name (`a-b.ts` and `a_b.ts`). `$`
    // never appears in a flattened name, so the suffix cannot clash either.
    let alias = base
    for (let n = 2; taken.has(alias); n++) alias = `${base}$${n}`

    taken.add(alias)
    modules.set(sourcePath, alias)
  }

  return modules
}

/** Type-level reference to a route's function, e.g. `typeof m_routes.ping`. */
function renderTypeRef(route: ExposedRoute, alias: string): string {
  return route.methodName
    ? `${alias}.${route.exportName}["${route.methodName}"]`
    : `typeof ${alias}.${route.exportName}`
}

function renderModuleImports(
  modules: Map<string, string>,
  outDir: string,
  keyword: "import" | "import type",
): string {
  return [...modules]
    .map(
      ([sourcePath, alias]) =>
        `${keyword} * as ${alias} from ${JSON.stringify(relativeImport(outDir, sourcePath))}`,
    )
    .join("\n")
}

function renderMain(
  routes: ExposedRoute[],
  modules: Map<string, string>,
  outDir: string,
  config: ResolvedElectronExposeConfig,
): string {
  // One instance per exposed class, named after its module alias so classes
  // with the same name in different files do not collide.
  const instances = new Map<string, string>()
  const handlers = routes.map((route) => {
    const alias = modules.get(route.sourcePath) as string
    let target = `${alias}.${route.exportName}`

    if (route.methodName) {
      const instance = `${alias}$${route.exportName}`
      instances.set(instance, `new ${alias}.${route.exportName}()`)
      target = `${instance}.${route.methodName}`
    }

    return [
      `  handle(${JSON.stringify(route.key)}, (...args) =>`,
      `    ${target}(...(args as Parameters<${renderTypeRef(route, alias)}>)),`,
      "  )",
    ].join("\n")
  })

  const instanceLines = [...instances]
    .map(([name, expression]) => `  const ${name} = ${expression}`)
    .join("\n")

  return `${HEADER}
import { ipcMain } from "electron"
${renderModuleImports(modules, outDir, "import")}

// Registers one route. A thrown error is logged here and sent back as data,
// because ipcMain.handle would otherwise wrap its message in
// "Error invoking remote method ...". The generated preload rethrows it.
function handle(key: string, handler: (...args: unknown[]) => unknown): void {
  const channel = ${JSON.stringify(`${config.routePrefix}:`)} + key

  ipcMain.handle(channel, async (_event, ...args: unknown[]) => {
    try {
      return { ok: true, value: await handler(...args) }
    } catch (error) {
      console.error(\`Error occurred in handler for '\${channel}':\`, error)
      const message = error instanceof Error ? error.message : String(error)
      return { ok: false, message }
    }
  })
}

export function registerElectronExposeRoutes() {
${instanceLines ? `${instanceLines}\n\n` : ""}${handlers.join("\n")}
}
`
}

function renderPreload(config: ResolvedElectronExposeConfig): string {
  return `${HEADER}
import { contextBridge, ipcRenderer } from "electron"
import { routeKeys } from "./types"
import type { ElectronExposeApi } from "./types"

type Reply = { ok: true; value: unknown } | { ok: false; message: string }

// Unwraps the reply from the generated main handler, so a failed call rejects
// with the original error message.
async function invoke(key: string, args: unknown[]): Promise<unknown> {
  const channel = ${JSON.stringify(`${config.routePrefix}:`)} + key
  const reply: Reply = await ipcRenderer.invoke(channel, ...args)
  if (!reply.ok) throw new Error(reply.message)
  return reply.value
}

function assignRoute(target: Record<string, unknown>, key: string, value: (...args: unknown[]) => Promise<unknown>) {
  const parts = key.split(".")
  let cursor = target

  for (const part of parts.slice(0, -1)) {
    cursor[part] = (cursor[part] ?? {}) as Record<string, unknown>
    cursor = cursor[part] as Record<string, unknown>
  }

  cursor[parts[parts.length - 1]] = value
}

export function exposeElectronApi() {
  const api: Record<string, unknown> = {}

  for (const key of routeKeys) {
    assignRoute(api, key, (...args: unknown[]) => invoke(key, args))
  }

  contextBridge.exposeInMainWorld(${JSON.stringify(config.globalApiName)}, api as ElectronExposeApi)
}
`
}

function renderTypes(
  routes: ExposedRoute[],
  modules: Map<string, string>,
  outDir: string,
): string {
  const lines = ["export type ElectronExposeApi = {"]
  renderTypeTree(buildTypeTree(routes), modules, lines, 1)
  lines.push("}")

  const routeKeys = routes.map((route) => `  "${route.key}",`).join("\n")

  return `${HEADER}
${renderModuleImports(modules, outDir, "import type")}

// The renderer-facing type of a route, derived from the function itself.
// Async functions pass through unchanged, which keeps their generics. Sync
// functions are wrapped, since every call crosses IPC and returns a Promise.
type Route<F extends (...args: never[]) => unknown> = [ReturnType<F>] extends [
  Promise<unknown>,
]
  ? F
  : (...args: Parameters<F>) => Promise<Awaited<ReturnType<F>>>

${lines.join("\n")}

export const routeKeys = [
${routeKeys}
] as const
`
}

type TypeTree = Map<string, TypeTree | ExposedRoute>

/** Nests routes by the dot-separated parts of their keys. */
function buildTypeTree(routes: ExposedRoute[]): TypeTree {
  const root: TypeTree = new Map()
  for (const route of routes) {
    const parts = route.key.split(".")
    let cursor = root
    for (const part of parts.slice(0, -1)) {
      // validateRoutes guarantees a parent key is never also a route.
      const next = (cursor.get(part) as TypeTree | undefined) ?? new Map()
      cursor.set(part, next)
      cursor = next
    }
    cursor.set(parts[parts.length - 1], route)
  }
  return root
}

function renderTypeTree(
  tree: TypeTree,
  modules: Map<string, string>,
  lines: string[],
  depth: number,
): void {
  const pad = "  ".repeat(depth)
  for (const [key, value] of tree) {
    if (value instanceof Map) {
      lines.push(`${pad}${key}: {`)
      renderTypeTree(value, modules, lines, depth + 1)
      lines.push(`${pad}}`)
      continue
    }

    for (const line of value.docs?.split("\n") ?? [])
      lines.push(`${pad}${line}`)
    const alias = modules.get(value.sourcePath) as string
    lines.push(`${pad}${key}: Route<${renderTypeRef(value, alias)}>`)
  }
}

/**
 * Renders a route's signature as the renderer sees it, for `list`. This is the
 * only place that asks the type checker for anything.
 */
function renderRouteSignature(route: ExposedRoute): string {
  const type = route.node.getType()
  const text = type.getText(route.node)
  const returns = type
    .getCallSignatures()[0]
    ?.getReturnType()
    .getText(route.node)

  if (!returns || returns.startsWith("Promise<") || !text.endsWith(returns)) {
    return text
  }
  return `${text.slice(0, -returns.length)}Promise<${returns}>`
}

function renderGlobal(
  globalPath: string,
  outDir: string,
  config: ResolvedElectronExposeConfig,
): string {
  // A name such as "my-api" is a valid window key but needs quoting here.
  const name = IDENTIFIER.test(config.globalApiName)
    ? config.globalApiName
    : JSON.stringify(config.globalApiName)

  return `${HEADER}
import type { ElectronExposeApi } from "${relativeImport(path.dirname(globalPath), path.join(outDir, "types.ts"))}"

declare global {
  interface Window {
    ${name}: ElectronExposeApi
  }
}

export {}
`
}

/** Import specifier from a directory to a TypeScript source file. */
function relativeImport(fromDir: string, toFile: string): string {
  let specifier = path
    .relative(fromDir, toFile.replace(/\.tsx?$/, ""))
    .replaceAll(path.sep, "/")
  if (!specifier.startsWith(".")) specifier = `./${specifier}`
  return specifier
}

function unique<T>(items: T[]): T[] {
  return [...new Set(items)]
}
